/**
 * לעברית יש 5 אותיות סופיות (ך ם ן ף ץ) שהן צורות מיקומיות של
 * (כ מ נ פ צ) - אותה אות בדיוק, רק כשהיא מופיעה בסוף מילה.
 *
 * במעגל האותיות אנחנו רוצים להציג רק את הצורה הבסיסית (למשל 'כ' ולא 'ך'),
 * אחרת המשתמש היה צריך לדעת מראש איפה בדיוק במילה האות תופיע - זה לא
 * הגיוני במשחק שבו מרכיבים מילים מאותיות "חופשיות".
 *
 * הפונקציות כאן מנרמלות אות (או מילה שלמה) לצורך השוואה מול המעגל,
 * ואילו האיות המקורי (עם הצורה הסופית הנכונה) תמיד נשמר לתצוגה ולניקוד.
 */

const FINAL_TO_BASE: Record<string, string> = {
  'ך': 'כ',
  'ם': 'מ',
  'ן': 'נ',
  'ף': 'פ',
  'ץ': 'צ',
};

export function normalizeFinalLetter(char: string): string {
  return FINAL_TO_BASE[char] ?? char;
}

export function normalizeWordLetters(word: string): string {
  return [...word].map(normalizeFinalLetter).join('');
}

/**
 * מחזירה את קבוצת האותיות הייחודיות במילה, אחרי נרמול צורות סופיות.
 * זו הפונקציה שמשמשת גם לבדיקת "אילו אותיות זמינות" וגם לזיהוי פנגרם.
 */
export function uniqueNormalizedLetters(word: string): Set<string> {
  return new Set(normalizeWordLetters(word));
}

const BASE_TO_FINAL: Record<string, string> = {
  'כ': 'ך',
  'מ': 'ם',
  'נ': 'ן',
  'פ': 'ף',
  'צ': 'ץ',
};

/**
 * ממירה את האות האחרונה של מילה לצורתה הסופית, אם צריך.
 *
 * למה זו נדרשת: מעגל האותיות מציג תמיד את הצורה הבסיסית (למשל 'מ'),
 * כי המשתמש לא יודע מראש אם האות שלו תהיה באמצע מילה או בסופה. אז
 * כשהוא גורר ובונה "עולמ" (עם 'מ' רגילה), זו בעצם הכוונה למילה "עולם"
 * (עם ם סופית) - כי בעברית תקנית אות סופית היא חובה בסוף מילה, לא בחירה.
 * בלי ההמרה הזו, החיפוש במילון היה נכשל על כל מילה שמסתיימת באחת מ-5
 * האותיות הסופיות, כי המחרוזת שהמשתמש "מקליד" לעולם לא תואמת בדיוק
 * לאיות המילוני האמיתי.
 *
 * שימי לב: ממירים רק את התו האחרון - אותיות סופיות באמצע מילה הן
 * שגיאת כתיב תמיד, אז אין צורך (ואסור) לגעת בשאר התווים.
 */
export function toFinalFormAtEnd(word: string): string {
  if (word.length === 0) return word;
  const chars = [...word];
  const last = chars[chars.length - 1];
  chars[chars.length - 1] = BASE_TO_FINAL[last] ?? last;
  return chars.join('');
}
